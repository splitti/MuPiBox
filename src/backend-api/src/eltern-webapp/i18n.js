const STORAGE_KEY = 'eltern.lang'
const SUPPORTED = ['de', 'en']

function readPref() {
  try {
    const v = localStorage.getItem(STORAGE_KEY)
    return SUPPORTED.includes(v) ? v : 'auto'
  } catch {
    return 'auto'
  }
}

function browserTags() {
  const tags = []
  try {
    if (Array.isArray(navigator.languages)) tags.push(...navigator.languages)
    if (navigator.language) tags.push(navigator.language)
  } catch {
    /* ignore */
  }
  return tags.map((x) => String(x || '').trim()).filter(Boolean)
}

/** Browser language: first tag whose primary subtag is de or en wins; else English. */
export function detectBrowserLanguage() {
  for (const tag of browserTags()) {
    const primary = tag.toLowerCase().split(/[-_]/)[0]
    if (SUPPORTED.includes(primary)) return primary
  }
  return 'en'
}

let pref = readPref()
let lang = pref === 'auto' ? detectBrowserLanguage() : pref

/** Active UI language ('de' | 'en'). */
export function getLang() {
  return lang
}

/** Stored preference ('auto' | 'de' | 'en'). */
export function getLangPref() {
  return pref
}

/** Change the preference, persist it (best effort) and return the active language. */
export function setLangPref(value) {
  pref = SUPPORTED.includes(value) ? value : 'auto'
  try {
    if (pref === 'auto') localStorage.removeItem(STORAGE_KEY)
    else localStorage.setItem(STORAGE_KEY, pref)
  } catch {
    /* private mode etc. — choice then only lasts for this page */
  }
  lang = pref === 'auto' ? detectBrowserLanguage() : pref
  document.documentElement.lang = lang
  return lang
}

/** Locale tag for toLocale*String / Intl. English follows the browser's
 *  English variant if there is one (en-US, en-GB, ...), else en-GB. */
export function localeTag() {
  if (lang === 'de') return 'de-DE'
  return (
    browserTags()
      .find((tag) => /^en([-_]|$)/i.test(tag))
      ?.replace('_', '-') ?? 'en-GB'
  )
}

/** Translate a key. vars fill {placeholders}; unknown placeholders stay as they are. */
export function t(key, vars) {
  let s = I18N[lang]?.[key] ?? I18N.en[key] ?? I18N.de[key]
  if (s == null) {
    console.warn('i18n: missing key', key)
    return key
  }
  if (vars) {
    s = s.replace(/\{(\w+)\}/g, (m, name) => (name in vars && vars[name] != null ? String(vars[name]) : m))
  }
  return s
}

/** Count-dependent text: uses <key>.one for n === 1, else <key>.other; {n} is filled in. */
export function tn(key, n, vars = {}) {
  return t(`${key}.${n === 1 ? 'one' : 'other'}`, { n, ...vars })
}

function readVars(el) {
  const raw = el.getAttribute('data-i18n-vars')
  if (!raw) return undefined
  try {
    return JSON.parse(raw)
  } catch {
    return undefined
  }
}

/** Fill every element below root that carries data-i18n (textContent),
 *  data-i18n-html (innerHTML, only for trusted dictionary texts),
 *  data-i18n-placeholder, data-i18n-title or data-i18n-aria-label. */
export function applyI18n(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n, readVars(el))
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml, readVars(el))
  for (const el of root.querySelectorAll('[data-i18n-placeholder]'))
    el.setAttribute('placeholder', t(el.dataset.i18nPlaceholder))
  for (const el of root.querySelectorAll('[data-i18n-title]')) el.setAttribute('title', t(el.dataset.i18nTitle))
  for (const el of root.querySelectorAll('[data-i18n-aria-label]'))
    el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel))
  if (root === document) document.documentElement.lang = lang
}
